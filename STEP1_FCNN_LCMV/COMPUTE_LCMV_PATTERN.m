function [THETA_DEG, RESPONSE, PATTERN_DB] = COMPUTE_LCMV_PATTERN( ...
    WEIGHTS, X_POSITIONS_M, Y_POSITIONS_M, FREQUENCY_HZ, ...
    THETA_MIN_DEG, THETA_MAX_DEG, NUM_SAMPLE_THETA, CUT_PHI_DEG)
% Evaluate the isotropic-element array response over one angular cut.

if NUM_SAMPLE_THETA < 2 || NUM_SAMPLE_THETA ~= round(NUM_SAMPLE_THETA)
    error('NUM_SAMPLE_THETA must be an integer greater than one.');
end
THETA_DEG = linspace(THETA_MIN_DEG, THETA_MAX_DEG, NUM_SAMPLE_THETA);
RESPONSE = complex(zeros(size(THETA_DEG)));
for SAMPLE_INDEX = 1:numel(THETA_DEG)
    STEERING_VECTOR = COMPUTE_LCMV_STEERING_VECTOR( ...
        X_POSITIONS_M, Y_POSITIONS_M, FREQUENCY_HZ, ...
        THETA_DEG(SAMPLE_INDEX), CUT_PHI_DEG);
    RESPONSE(SAMPLE_INDEX) = WEIGHTS' * STEERING_VECTOR;
end
PATTERN_DB = 20*log10(max(abs(RESPONSE), 1e-12));
PATTERN_DB = PATTERN_DB - max(PATTERN_DB);
end
