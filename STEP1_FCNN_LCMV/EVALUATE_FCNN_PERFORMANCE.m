function [METRICS, SUMMARY] = EVALUATE_FCNN_PERFORMANCE( ...
    INPUTS, WEIGHTS_LCMV, WEIGHTS_FCNN, ...
    X_POSITIONS_M, Y_POSITIONS_M, FREQUENCY_HZ, PHI_DEG, ...
    SIGNAL_POWER, NOISE_POWER, INT_POWER, ...
    GAIN_TOLERANCE_DB, NULL_DEPTH_TARGET_DB)
% Compare the FCNN weights with the reference LCMV weights, example by
% example. The array response convention is the one of the LCMV code:
% RESPONSE(theta) = WEIGHTS' * STEERING_VECTOR(theta).
%
% PER-EXAMPLE METRICS (for both LCMV and FCNN unless stated)
%   DES_GAIN_DB      20*log10|w' a(THETA_DES)|        target: 0 dB
%   DES_PHASE_DEG    angle(w' a(THETA_DES))           target: 0 deg
%   NULL_DEPTH_DB    20*log10(|w' a(THETA_INT)| / |w' a(THETA_DES)|)
%                    response toward the interferer relative to the
%                    desired response (more negative = deeper null)
%   SINR_DB          output SINR = Ps |w' a_d|^2 / (w' R_in w), with
%                    R_in = Pn I + Pi a_i a_i' (true noise + interference)
%   WEIGHT_NMSE_DB   10*log10(||w_FCNN - w_LCMV||^2 / ||w_LCMV||^2) (FCNN)
%   SINR_LOSS_DB     SINR_LCMV - SINR_FCNN                          (FCNN)
%   SUCCESS          |DES_GAIN_DB| <= GAIN_TOLERANCE_DB and
%                    NULL_DEPTH_DB <= NULL_DEPTH_TARGET_DB           (FCNN)

NUM_EXAMPLES = size(INPUTS, 1);
NUM_ELEMENTS = size(WEIGHTS_LCMV, 2);
MIN_AMPLITUDE = 1e-15;                 % avoids log10(0) for exact nulls

METHOD_NAMES = {'LCMV', 'FCNN'};
WEIGHTS_ALL = {WEIGHTS_LCMV, WEIGHTS_FCNN};

for METHOD_INDEX = 1:2
    WEIGHTS = WEIGHTS_ALL{METHOD_INDEX};
    DES_GAIN_DB = zeros(NUM_EXAMPLES, 1);
    DES_PHASE_DEG = zeros(NUM_EXAMPLES, 1);
    NULL_DEPTH_DB = zeros(NUM_EXAMPLES, 1);
    SINR_DB = zeros(NUM_EXAMPLES, 1);

    for EXAMPLE_INDEX = 1:NUM_EXAMPLES
        W = WEIGHTS(EXAMPLE_INDEX, :).';
        STEERING_DES = COMPUTE_LCMV_STEERING_VECTOR(X_POSITIONS_M, ...
            Y_POSITIONS_M, FREQUENCY_HZ, INPUTS(EXAMPLE_INDEX, 1), PHI_DEG);
        STEERING_INT = COMPUTE_LCMV_STEERING_VECTOR(X_POSITIONS_M, ...
            Y_POSITIONS_M, FREQUENCY_HZ, INPUTS(EXAMPLE_INDEX, 2), PHI_DEG);

        RESPONSE_DES = W' * STEERING_DES;
        RESPONSE_INT = W' * STEERING_INT;

        DES_GAIN_DB(EXAMPLE_INDEX) = 20*log10(max(abs(RESPONSE_DES), MIN_AMPLITUDE));
        DES_PHASE_DEG(EXAMPLE_INDEX) = rad2deg(angle(RESPONSE_DES));
        NULL_DEPTH_DB(EXAMPLE_INDEX) = 20*log10( ...
            max(abs(RESPONSE_INT), MIN_AMPLITUDE) / ...
            max(abs(RESPONSE_DES), MIN_AMPLITUDE));

        % .. Output SINR with the true (unloaded) covariance ..
        COVARIANCE_IN = NOISE_POWER*eye(NUM_ELEMENTS) + ...
            INT_POWER*(STEERING_INT*STEERING_INT');
        SINR_DB(EXAMPLE_INDEX) = 10*log10(SIGNAL_POWER*abs(RESPONSE_DES)^2 / ...
            real(W' * COVARIANCE_IN * W));
    end

    METRICS.(METHOD_NAMES{METHOD_INDEX}).DES_GAIN_DB = DES_GAIN_DB;
    METRICS.(METHOD_NAMES{METHOD_INDEX}).DES_PHASE_DEG = DES_PHASE_DEG;
    METRICS.(METHOD_NAMES{METHOD_INDEX}).NULL_DEPTH_DB = NULL_DEPTH_DB;
    METRICS.(METHOD_NAMES{METHOD_INDEX}).SINR_DB = SINR_DB;
end

%% .. FCNN-specific comparison with the LCMV reference ..
WEIGHT_ERROR = sum(abs(WEIGHTS_FCNN - WEIGHTS_LCMV).^2, 2);
WEIGHT_ENERGY = sum(abs(WEIGHTS_LCMV).^2, 2);
METRICS.FCNN.WEIGHT_NMSE_DB = 10*log10(WEIGHT_ERROR ./ WEIGHT_ENERGY);
METRICS.FCNN.SINR_LOSS_DB = METRICS.LCMV.SINR_DB - METRICS.FCNN.SINR_DB;
METRICS.FCNN.SUCCESS = abs(METRICS.FCNN.DES_GAIN_DB) <= GAIN_TOLERANCE_DB & ...
    METRICS.FCNN.NULL_DEPTH_DB <= NULL_DEPTH_TARGET_DB;

%% .. Summary statistics over all examples ..
SUMMARY.NUM_EXAMPLES = NUM_EXAMPLES;
SUMMARY.LCMV_DES_GAIN_DB = SUMMARIZE(METRICS.LCMV.DES_GAIN_DB);
SUMMARY.LCMV_NULL_DEPTH_DB = SUMMARIZE(METRICS.LCMV.NULL_DEPTH_DB);
SUMMARY.LCMV_SINR_DB = SUMMARIZE(METRICS.LCMV.SINR_DB);
SUMMARY.FCNN_DES_GAIN_DB = SUMMARIZE(METRICS.FCNN.DES_GAIN_DB);
SUMMARY.FCNN_ABS_DES_GAIN_DB = SUMMARIZE(abs(METRICS.FCNN.DES_GAIN_DB));
SUMMARY.FCNN_ABS_DES_PHASE_DEG = SUMMARIZE(abs(METRICS.FCNN.DES_PHASE_DEG));
SUMMARY.FCNN_NULL_DEPTH_DB = SUMMARIZE(METRICS.FCNN.NULL_DEPTH_DB);
SUMMARY.FCNN_SINR_DB = SUMMARIZE(METRICS.FCNN.SINR_DB);
SUMMARY.FCNN_SINR_LOSS_DB = SUMMARIZE(METRICS.FCNN.SINR_LOSS_DB);
SUMMARY.FCNN_WEIGHT_NMSE_DB = SUMMARIZE(METRICS.FCNN.WEIGHT_NMSE_DB);
SUMMARY.FCNN_NULL_BELOW_TARGET_PCT = 100*mean( ...
    METRICS.FCNN.NULL_DEPTH_DB <= NULL_DEPTH_TARGET_DB);
SUMMARY.FCNN_GAIN_WITHIN_TOL_PCT = 100*mean( ...
    abs(METRICS.FCNN.DES_GAIN_DB) <= GAIN_TOLERANCE_DB);
SUMMARY.FCNN_SUCCESS_PCT = 100*mean(METRICS.FCNN.SUCCESS);
SUMMARY.GAIN_TOLERANCE_DB = GAIN_TOLERANCE_DB;
SUMMARY.NULL_DEPTH_TARGET_DB = NULL_DEPTH_TARGET_DB;
end

function STATS = SUMMARIZE(VALUES)
% Mean, median, 5th/95th percentiles, minimum and maximum of a metric.
SORTED_VALUES = sort(VALUES(:));
STATS.MEAN = mean(SORTED_VALUES);
STATS.MEDIAN = median(SORTED_VALUES);
STATS.P05 = SORTED_VALUES(max(1, ceil(0.05*numel(SORTED_VALUES))));
STATS.P95 = SORTED_VALUES(max(1, ceil(0.95*numel(SORTED_VALUES))));
STATS.MIN = SORTED_VALUES(1);
STATS.MAX = SORTED_VALUES(end);
end
